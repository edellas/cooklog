export function trovaMestiere(id) {
  return MESTIERI.find((m) => m.id === id) || null;
}

// Converte le voci compatte in oggetti listino.
export function vociListino(mestiere) {
  if (!mestiere) return [];
  return mestiere.voci.map(([descrizione, um, prezzo, tipo]) => ({
    descrizione,
    um,
    prezzo,
    tipo,
  }));
}
